// tools/build.mjs: package the game as an installable, offline-capable web app in dist/ (GitHub Pages ready).
//   node tools/build.mjs            -> dist/  (only the files the game loads, plus sw.js and .nojekyll)
// Shipped files are found by walking the ES-module import graph from the HTML entry scripts, so the unused
// three.js builds and addons in vendor/ (and .review/, tests/, tools/) never get published.
import { readFileSync, writeFileSync, mkdirSync, rmSync, copyFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join, posix } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');
const html = readFileSync(join(root, 'index.html'), 'utf8');

// the importmap in index.html: bare specifiers -> project paths
const map = JSON.parse(html.match(/<script type="importmap">([\s\S]*?)<\/script>/)[1]).imports;
function resolve(spec, from) {
  if (spec.startsWith('.')) return posix.normalize(posix.join(posix.dirname(from), spec));
  if (map[spec]) return posix.normalize(map[spec]);
  const pre = Object.keys(map).find((k) => k.endsWith('/') && spec.startsWith(k));
  if (pre) return posix.normalize(map[pre] + spec.slice(pre.length));
  throw new Error(`unresolved import "${spec}" in ${from}`);
}

const files = new Set(['index.html', 'styles.css', 'manifest.webmanifest']);
for (const f of readdirSync(join(root, 'icons'))) files.add('icons/' + f);
// entry modules: every <script type="module" src> in index.html, plus all of src/ (some are loaded with import())
const queue = [...html.matchAll(/<script[^>]*type="module"[^>]*src="([^"]+)"/g)].map((m) => posix.normalize(m[1]));
for (const f of readdirSync(join(root, 'src'))) if (f.endsWith('.js')) queue.push('src/' + f);
const IMPORT_RE = /(?:import|export)\s*(?:[\w*{}\s,$]+from\s*)?['"]([^'"]+)['"]|import\(\s*['"]([^'"]+)['"]\s*\)/g;
while (queue.length) {
  const f = queue.pop();
  if (files.has(f)) continue;
  files.add(f);
  const src = readFileSync(join(root, f), 'utf8');
  for (const m of src.matchAll(IMPORT_RE)) {
    const dep = resolve(m[1] || m[2], f);
    if (!files.has(dep)) queue.push(dep);
  }
}
for (const f of files) if (!existsSync(join(root, f))) throw new Error('missing file: ' + f);

rmSync(dist, { recursive: true, force: true });
const hash = createHash('sha256');
const list = [...files].sort();
for (const f of list) {
  mkdirSync(dirname(join(dist, f)), { recursive: true });
  copyFileSync(join(root, f), join(dist, f));
  hash.update(f).update(readFileSync(join(root, f)));
}
const version = hash.digest('hex').slice(0, 12);
// stamp the build into the page (Settings → App version), so a device can show which build it is running
const stamp = `${new Date().toISOString().slice(0, 10)} · ${version.slice(0, 7)}`;
writeFileSync(join(dist, 'index.html'), readFileSync(join(dist, 'index.html'), 'utf8').replace('<meta name="app-version" content="dev">', `<meta name="app-version" content="${stamp}">`));

// service worker: precache everything, serve cache-first (the game is fully static), new version = new cache
writeFileSync(join(dist, 'sw.js'), `// generated by tools/build.mjs: do not edit
const VERSION = 'craps-${version}';
const FILES = ${JSON.stringify(['./', ...list], null, 0)};
self.addEventListener('install', (e) => {
  // cache: 'reload' skips the browser's HTTP cache: GitHub Pages sends max-age=600, so a plain fetch could fill
  // the NEW version's cache with the PREVIOUS deploy's files for up to 10 minutes after an update
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(FILES.map((u) => new Request(u, { cache: 'reload' })))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  // only this app's old caches: the Lite table (lite/) keeps its own cache on the same origin
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('craps-') && k !== VERSION).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
const LITE = new URL('lite/', self.registration.scope).pathname;
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  // the Lite table is its own app (lite/sw.js); never answer its page with this one
  if (req.mode === 'navigate' && new URL(req.url).pathname.startsWith(LITE)) return;
  e.respondWith((async () => {
    const cache = await caches.open(VERSION);
    const hit = req.mode === 'navigate' ? await cache.match('./') : await cache.match(req, { ignoreSearch: true });
    return hit || fetch(req);
  })());
});
`);
writeFileSync(join(dist, '.nojekyll'), '');

// ---------- the Lite table: lite/ -> dist/lite/, its own offline cache (lite/sw.js, scope lite/) ----------
{
  const liteHtml = readFileSync(join(root, 'lite/index.html'), 'utf8');
  const lf = new Set(['lite/index.html', 'lite/lite.css', 'lite/manifest.webmanifest', 'lite/icon-192.png', 'lite/icon-512.png']);
  const q = [...liteHtml.matchAll(/<script[^>]*type="module"[^>]*src="([^"]+)"/g)].map((m) => posix.normalize('lite/' + m[1]));
  while (q.length) {
    const f = q.pop(); if (lf.has(f)) continue; lf.add(f);
    for (const m of readFileSync(join(root, f), 'utf8').matchAll(IMPORT_RE)) { const spec = m[1] || m[2]; if (spec.startsWith('.')) q.push(posix.normalize(posix.join(posix.dirname(f), spec))); else throw new Error('lite: bare import ' + spec); }
  }
  const lh = createHash('sha256'), ll = [...lf].sort();
  for (const f of ll) { mkdirSync(dirname(join(dist, f)), { recursive: true }); copyFileSync(join(root, f), join(dist, f)); lh.update(f).update(readFileSync(join(root, f))); }
  const lv = lh.digest('hex').slice(0, 12);
  writeFileSync(join(dist, 'lite/index.html'), liteHtml.split('<meta name="app-version" content="dev">').join(`<meta name="app-version" content="${new Date().toISOString().slice(0, 10)} · ${lv.slice(0, 7)}">`));
  const rel = ['./', ...ll.filter((f) => f !== 'lite/index.html').map((f) => (f.startsWith('lite/') ? f.slice(5) : '../' + f))];
  writeFileSync(join(dist, 'lite/sw.js'), `// generated by tools/build.mjs: do not edit
const VERSION = 'lite-${lv}';
const FILES = ${JSON.stringify(rel)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(FILES.map((u) => new Request(u, { cache: 'reload' })))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('lite-') && k !== VERSION).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith((async () => {
    const cache = await caches.open(VERSION);
    const hit = req.mode === 'navigate' ? await cache.match('./') : await cache.match(req, { ignoreSearch: true });
    return hit || fetch(req);
  })());
});
`);
  console.log(`dist/lite/: ${ll.length} files, cache version ${lv}`);
}
const bytes = list.reduce((s, f) => s + readFileSync(join(root, f)).length, 0);
console.log(`dist/: ${list.length} files, ${(bytes / 1048576).toFixed(1)} MB, cache version ${version}`);
